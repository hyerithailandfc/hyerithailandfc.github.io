// Site validator — run with `node tools/validate.mjs` (Node 18+). Exits 1 on any error.
// Checks: JSON syntax, i18n key parity, page registry, localized fields, media files.
import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const errors = [];
const warnings = [];
const LANGS = ['th', 'en', 'ko'];

function readJSON(rel) {
  try {
    return JSON.parse(readFileSync(join(root, rel), 'utf8'));
  } catch (e) {
    errors.push(`${rel}: invalid JSON — ${e.message}`);
    return null;
  }
}

function walkFiles(dir) {
  return readdirSync(join(root, dir)).flatMap((name) => {
    const rel = `${dir}/${name}`;
    return statSync(join(root, rel)).isDirectory() ? walkFiles(rel) : [rel];
  });
}

// 1. Every JSON file under data/ must parse.
const dataFiles = walkFiles('data').filter((f) => f.endsWith('.json'));
const data = Object.fromEntries(dataFiles.map((f) => [f, readJSON(f)]));

// 2. i18n files must have identical key sets.
function keys(obj, prefix = '') {
  return Object.entries(obj || {}).flatMap(([k, v]) =>
    v && typeof v === 'object' ? keys(v, `${prefix}${k}.`) : [`${prefix}${k}`]);
}
const i18n = Object.fromEntries(LANGS.map((l) => [l, data[`data/i18n/${l}.json`]]));
if (LANGS.every((l) => i18n[l])) {
  const sets = Object.fromEntries(LANGS.map((l) => [l, new Set(keys(i18n[l]))]));
  const all = new Set(LANGS.flatMap((l) => [...sets[l]]));
  for (const k of all) {
    const missing = LANGS.filter((l) => !sets[l].has(k));
    if (missing.length) errors.push(`i18n key "${k}" missing in: ${missing.join(', ')}`);
  }
}

// 3. Page registry.
const site = data['data/site.json'];
if (site) {
  const ids = new Set();
  const paths = new Set();
  for (const p of site.pages || []) {
    const where = `site.json page "${p.id}"`;
    if (!p.id || !p.path || !p.module) errors.push(`${where}: needs id, path and module`);
    if (ids.has(p.id)) errors.push(`${where}: duplicate id`);
    if (paths.has(p.path)) errors.push(`${where}: duplicate path ${p.path}`);
    ids.add(p.id); paths.add(p.path);
    if (p.path && !p.path.startsWith('/')) errors.push(`${where}: path must start with "/"`);
    for (const l of LANGS) if (!p.label?.[l]) errors.push(`${where}: label.${l} missing`);
    const file = join(root, 'assets/js/pages', p.module || '');
    if (!existsSync(file)) errors.push(`${where}: module assets/js/pages/${p.module} not found`);
    else if (!/export\s+(async\s+)?function\s+render\s*\(/.test(readFileSync(file, 'utf8'))) {
      errors.push(`${where}: module must export function render()`);
    }
  }
}

// 4. Localized values in content files: need en + ko; th is recommended for prose.
const PROSE_KEYS = new Set(['body', 'desc', 'note', 'category', 'role', 'caption', 'family', 'birthplace', 'position']);
function checkLocalized(value, path, file) {
  if (Array.isArray(value)) { value.forEach((v, i) => checkLocalized(v, `${path}[${i}]`, file)); return; }
  if (!value || typeof value !== 'object') return;
  const ks = Object.keys(value);
  const isLang = ks.length > 0 && ks.every((k) => LANGS.includes(k));
  if (isLang) {
    for (const l of ['en', 'ko']) if (!value[l]) errors.push(`${file} ${path}: "${l}" text missing`);
    const last = path.split('.').pop().replace(/\[\d+\]$/, '');
    if (!value.th && PROSE_KEYS.has(last)) warnings.push(`${file} ${path}: Thai text missing (falls back to English)`);
    return;
  }
  for (const [k, v] of Object.entries(value)) checkLocalized(v, path ? `${path}.${k}` : k, file);
}
// data/tmdb.json and data/youtube.json are generated by tools/sync-external.mjs — their translations can legitimately be empty.
const GENERATED = new Set(['data/tmdb.json', 'data/youtube.json']);
for (const f of dataFiles.filter((f) => !f.startsWith('data/i18n/') && f !== 'data/site.json' && !GENERATED.has(f))) {
  if (data[f]) checkLocalized(data[f], '', f);
}

// 4b. Optional pins in works.json that link entries to TMDB / YouTube.
const works = data['data/works.json'];
if (works) {
  for (const kind of ['drama', 'movie']) {
    for (const w of works[kind] || []) {
      if (w.tmdbId != null && !Number.isInteger(w.tmdbId)) errors.push(`works.json ${kind} "${w.title?.en}": tmdbId must be a number`);
    }
  }
  for (const m of works.mv || []) {
    if (m.youtubeId != null && !/^[\w-]{11}$/.test(m.youtubeId)) errors.push(`works.json mv "${m.song?.en}": bad youtubeId "${m.youtubeId}"`);
  }
}
const girlsday = data['data/girlsday.json'];
if (girlsday) {
  const TYPES = new Set(Object.keys(i18n.en?.gd?.type || {}));
  for (const r of girlsday.releases || []) {
    const where = `girlsday.json release "${r.title?.en}"`;
    if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date || '')) errors.push(`${where}: date must be YYYY-MM-DD`);
    if (!TYPES.has(r.type)) errors.push(`${where}: type "${r.type}" has no gd.type.* UI string`);
    if (r.youtubeId != null && !/^[\w-]{11}$/.test(r.youtubeId)) errors.push(`${where}: bad youtubeId "${r.youtubeId}"`);
  }
}

// 5. Media files referenced by data/media.json must exist; YouTube ids must look valid.
const media = data['data/media.json'];
if (media) {
  for (const g of media.gallery || []) {
    if (!g.src || !existsSync(join(root, g.src))) errors.push(`media.json gallery: file not found "${g.src}"`);
    if (/^https?:/.test(g.src || '')) errors.push(`media.json gallery: "${g.src}" must be a file in this repo, not a hotlink`);
  }
  // "From her works" order: TMDB stills by path ({ tmdb: "/x.jpg" }) or admin uploads (same rules as gallery).
  for (const g of media.workGallery || []) {
    if (g.tmdb) { if (!/^\/[\w-]+\.(jpg|png)$/.test(g.tmdb)) errors.push(`media.json workGallery: bad TMDB path "${g.tmdb}"`); continue; }
    if (!g.src || /^https?:/.test(g.src) || !existsSync(join(root, g.src))) errors.push(`media.json workGallery: file not found "${g.src}"`);
  }
  for (const v of media.videos || []) {
    if (!/^[\w-]{11}$/.test(v.id || '')) errors.push(`media.json videos: bad YouTube id "${v.id}"`);
  }
}

for (const w of warnings) console.log(`warn  ${w}`);
for (const e of errors) console.log(`ERROR ${e}`);
console.log(errors.length ? `\n✖ ${errors.length} error(s)` : `✔ Site data is valid (${warnings.length} warning(s))`);
process.exit(errors.length ? 1 : 0);
